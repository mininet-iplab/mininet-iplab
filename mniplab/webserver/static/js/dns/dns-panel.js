async function refreshDnssec() {
    const node = currentNode;
    const zone = currentZone;
    if (!node || !zone) return;
    const requestId = ++dnssecRefreshId;

    let response;
    try {
        response = await getDnsZoneDnssec(node, zone);
    } catch (error) {
        if (node === currentNode) {
            setDnssecStatus(`Can't reach the server: ${error.message || error}`, true);
        }
        return;
    }

    if (node !== currentNode || zone !== currentZone || requestId !== dnssecRefreshId) return;

    let data = null;
    try {
        data = await response.json();
    } catch (_) { /* fall through with data === null */ }

    if (node !== currentNode || zone !== currentZone || requestId !== dnssecRefreshId) return;

    if (!response.ok) {
        clearDnssec();
        setDnssecStatus(
            formatResponseError(data, `Request failed (${response.status})`),
            true,
        );
        return;
    }

    renderDnssec(data);
}

/** Render one Zone's DNSSEC state: the Signed badge, the signing summary, the
 * keys signing it, and the DS a parent Zone needs.
 *
 * An unsigned Zone hides the whole section rather than showing it empty —
 * there is nothing about it that DNSSEC explains.
 *
 * Args:
 *     details: The payload of GET /api/dns/{node}/zones/{zone}/dnssec.
 */
export function renderDnssec(details) {
    const signed = Boolean(details && details.dnssec);
    const section = document.getElementById('dns-dnssec-section');
    const badge = document.getElementById('dns-zone-signed-badge');
    const toggle = document.getElementById('dns-dnssec-records-toggle');
    if (section) section.hidden = !signed;
    if (badge) badge.hidden = !signed;
    if (toggle) toggle.hidden = !signed;

    // A render clears only what a render put there. The clipboard's own
    // message — above all the refusal, which tells a Learner to copy the DS by
    // hand — has to outlive the next poll, or it is gone before it is read.
    clearTransientDnssecStatus();

    if (!signed) {
        renderDnssecKeys([]);
        renderDsRecords([]);
        return;
    }

    setText('dns-dnssec-signing', 'Signed by Knot (automatic KASP signing)');
    setText(
        'dns-dnssec-denial',
        details.nsec3
            ? `NSEC3${details.nsec3_salt ? ` (salt ${details.nsec3_salt})` : ''}`
            : 'NSEC',
    );
    renderDnssecKeys(details.keys || []);
    renderDsRecords(details.ds_records || []);
}

function renderDnssecKeys(keys) {
    const tbody = document.getElementById('dns-dnssec-keys-tbody');
    if (!tbody) return;
    patchTableRows(tbody, keys.map((key) => ({
        key: String(key.tag),
        cells: [
            String(key.tag ?? '—'),
            key.ksk ? 'KSK' : (key.zsk ? 'ZSK' : '—'),
            describeAlgorithm(key.algorithm),
            key.active ? 'active' : 'published',
        ],
    })));
}

/** List each DS beside a button that copies it in presentation format.
 *
 * The clipboard is the point: the DS has to reach the parent Zone's Record
 * editor intact, and a 64-character hex digest retyped by hand is the most
 * reliable way to break the chain of trust this lab is teaching.
 *
 * Args:
 *     dsRecords: The DS Records the Zone's KSK generates.
 */
function renderDsRecords(dsRecords) {
    const list = document.getElementById('dns-dnssec-ds-list');
    if (!list) return;
    list.replaceChildren();

    if (dsRecords.length === 0) {
        const item = document.createElement('li');
        item.className = 'dns-dnssec-ds-empty';
        item.textContent = 'No DS Record has been generated for this Zone yet.';
        list.appendChild(item);
        return;
    }

    dsRecords.forEach((ds) => {
        const item = document.createElement('li');
        item.className = 'dns-dnssec-ds-item';

        const rdata = formatDsRecord(ds);
        const text = document.createElement('code');
        text.className = 'dns-dnssec-ds-rdata';
        text.textContent = `${ds.owner || ''} IN DS ${rdata}`.trim();
        item.appendChild(text);

        const button = document.createElement('button');
        button.type = 'button';
        button.className = 'dns-record-action-btn dns-dnssec-copy-btn';
        button.textContent = 'Copy DS';
        button.setAttribute(
            'aria-label',
            `Copy the DS record for key tag ${ds.key_tag} to the clipboard`,
        );
        button.addEventListener('click', () => { void copyDsRecord(rdata); });
        item.appendChild(button);

        list.appendChild(item);
    });
}

/** Put one DS's RDATA on the clipboard, saying so in the section's status.
 *
 * A browser refuses the clipboard outside a secure context, which a Lab served
 * over plain HTTP from another host is; the RDATA is already on screen, so the
 * failure says to copy it from there rather than pretending it worked. */
async function copyDsRecord(rdata) {
    try {
        await navigator.clipboard.writeText(rdata);
        setDnssecStatus('DS record copied to the clipboard.', false, { sticky: true });
    } catch (error) {
        setDnssecStatus(
            'The browser refused clipboard access; select the DS record above and copy it.',
            true,
            { sticky: true },
        );
    }
}

/** Put one message in the DNSSEC section's status line.
 *
 * Args:
 *     message: What to say, or '' to clear.
 *     isError: Whether to style it as a failure.
 *     sticky: Whether it survives the next render. A message a Learner's own
 *         action produced is sticky; one the panel's polling produced is not.
 */
function setDnssecStatus(message, isError, { sticky = false } = {}) {
    const el = document.getElementById('dns-dnssec-status');
    if (!el) return;
    el.textContent = message;
    el.classList.toggle('dns-modal-status-error', Boolean(isError && message));
    el.dataset.sticky = message && sticky ? '1' : '';
}

function clearTransientDnssecStatus() {
    const el = document.getElementById('dns-dnssec-status');
    if (!el || el.dataset.sticky === '1') return;
    setDnssecStatus('', false);
}

function clearDnssec() {
    setDnssecStatus('', false);
    renderDnssec(null);
    setText('dns-dnssec-signing', '—');
    setText('dns-dnssec-denial', '—');
}

export function handleDnsRecordBroadcast(data) {
    if (!data || !currentNode || data.node !== currentNode) return;
    // Last-write-wins: a Record another session committed replaces what this
    // panel shows. The table holds the selected Zone only, so a broadcast for
    // another Zone refreshes the Status panel alone.
    if (data.zone && data.zone === currentZone) {
        if (editingRecord) {
            resetRecordForm();
            setRecordsStatus('The Zone changed; the edit form was reset.', false);
        }
        void refreshRecords();
    }
    void refreshZoneStatus();
}
