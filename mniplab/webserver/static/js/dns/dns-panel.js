const POLL_INTERVAL_MS = 3000;

let currentNode = null;
let currentZone = null;
let currentRole = 'primary';
let currentPrimary = null;
let pollTimer = null;
let trap = null;
let recordsRefreshId = 0;
let transfersRefreshId = 0;
// The Record being edited, or null when the form is in Add mode. Editing
// re-uses the Add form: the original Record is removed and the submitted
// values committed as a fresh set, because a set alone would leave the old
// RDATA in place when the edit changed it.
let editingRecord = null;
// Every Record the selected Zone holds, as last polled. Held so the signature
// toggle can re-render without a round trip.
let allRecords = [];
let dnssecRefreshId = 0;

export const SIGNATURE_RECORD_TYPES = ['RRSIG', 'NSEC', 'NSEC3', 'NSEC3PARAM'];

/** The Records the table shows.
 *
 * RRSIG and the NSEC chain are generated by Knot's signer, not authored, and
 * are regenerated wholesale whenever the Zone changes — so they are hidden
 * unless a Learner asks for them. NSEC3 and its NSEC3PARAM are the same
 * output under the other denial scheme, and hide with them.
 *
 * Args:
 *     records: Every Record the Zone holds.
 *     showSignatures: Whether to include the signer's own output.
 *
 * Returns:
 *     The Records to render, in the order given.
 */
export function visibleRecords(records, showSignatures) {
    if (showSignatures) return records;
    return records.filter(
        (record) => !SIGNATURE_RECORD_TYPES.includes(String(record.type || '').toUpperCase())
    );
}

/** DNSSEC algorithm numbers by their IANA mnemonic, so a key reads as
 * "ECDSAP256SHA256 (13)" rather than as a bare number. */
const DNSSEC_ALGORITHMS = {
    5: 'RSASHA1',
    7: 'RSASHA1-NSEC3-SHA1',
    8: 'RSASHA256',
    10: 'RSASHA512',
    13: 'ECDSAP256SHA256',
    14: 'ECDSAP384SHA384',
    15: 'ED25519',
    16: 'ED448',
};

/** One DNSSEC algorithm as a Learner reads it.
 *
 * Args:
 *     algorithm: The IANA algorithm number from a key or DS Record.
 *
 * Returns:
 *     The mnemonic and number, e.g. "ECDSAP256SHA256 (13)"; the bare number
 *     when the mnemonic is not one this Lab knows, and "—" when there is no
 *     number at all.
 */
export function describeAlgorithm(algorithm) {
    const number = Number(algorithm);
    if (!Number.isInteger(number)) return '—';
    const name = DNSSEC_ALGORITHMS[number];
    return name ? `${name} (${number})` : String(number);
}

/** One DS Record as its presentation format, which is what a parent Zone's
 * Record editor expects pasted into its Data field. */
export function formatDsRecord(ds) {
    return [ds.key_tag, ds.algorithm, ds.digest_type, ds.digest].join(' ');
}

export function initDnsPanel() {
    const modal = document.getElementById('dns-modal');
    const closeBtn = document.getElementById('dns-modal-close');
    if (!modal) return;

    if (closeBtn) closeBtn.addEventListener('click', closeDnsPanel);
    modal.addEventListener('click', (event) => {
        if (event.target === modal) closeDnsPanel();
    });

    const zoneSelect = document.getElementById('dns-zone-select');
    if (zoneSelect) {
        zoneSelect.addEventListener('change', () => {
            currentZone = zoneSelect.value || null;
            recordsRefreshId += 1;
            resetRecordForm();
            void refreshRecords();
            void refreshZoneStatus();
            void refreshDnssec();
        });
    }

    const signatureToggle = document.getElementById('dns-show-dnssec-records');
    if (signatureToggle) {
        signatureToggle.addEventListener('change', () => renderRecords(allRecords));
    }

    const form = document.getElementById('dns-record-form');
    if (form) {
        form.addEventListener('submit', (event) => {
            event.preventDefault();
            void handleRecordSubmit();
        });
    }

    const cancelBtn = document.getElementById('dns-record-cancel');
    if (cancelBtn) {
        cancelBtn.addEventListener('click', () => resetRecordForm());
    }

    const resetBtn = document.getElementById('dns-stats-reset');
    if (resetBtn) {
        resetBtn.addEventListener('click', () => { void handleStatsReset(); });
    }

    const refreshBtn = document.getElementById('dns-btn-refresh');
    if (refreshBtn) {
        refreshBtn.addEventListener('click', () => { void handleSecondaryRefresh(); });
    }

    const retransferBtn = document.getElementById('dns-btn-retransfer');
    if (retransferBtn) {
        retransferBtn.addEventListener('click', () => { void handleSecondaryRetransfer(); });
    }

    const primaryLink = document.getElementById('dns-primary-link');
    if (primaryLink) {
        primaryLink.addEventListener('click', () => {
            if (currentPrimary && !/^\d+\.\d+\.\d+\.\d+$/.test(currentPrimary) && !currentPrimary.includes(':')) {
                openDnsPanel(currentPrimary);
            }
        });
    }
}

let editTriggerButton = null;

export function openDnsPanel(nodeName) {
    const modal = document.getElementById('dns-modal');
    const title = document.getElementById('dns-modal-title');
    if (!modal) return;

    currentNode = nodeName;
    currentZone = null;
    currentRole = 'primary';
    currentPrimary = null;
    recordsRefreshId += 1;
    transfersRefreshId += 1;
    dnssecRefreshId += 1;
    if (title) title.textContent = `${nodeName} — DNS Service`;
    resetRecordForm();
    clearRecords();
    clearDnssec();
    clearStats();
    clearZoneStatus();
    clearTransfers();
    clearSecondaryUI();
    setRecordsStatus('Loading Zones…', false);

    modal.style.display = 'flex';
    // Re-opening while already open (another badge press) must not leak the
    // previous trap's document-level listener.
    if (trap) trap.release();
    trap = trapFocus(modal, { onClose: closeDnsPanel });

    void loadZones();
    void refreshStats();
    if (pollTimer) clearInterval(pollTimer);
    pollTimer = setInterval(() => {
        void refreshZoneStatus();
        void refreshStats();
        // A key rollover run from the CLI changes the key set without touching
        // any Record, so the DNSSEC panel has to poll to notice it.
        void refreshDnssec();
    }, POLL_INTERVAL_MS);
}

export function closeDnsPanel() {
    const modal = document.getElementById('dns-modal');
    if (modal) modal.style.display = 'none';
    if (pollTimer) {
        clearInterval(pollTimer);
        pollTimer = null;
    }
    currentNode = null;
    currentZone = null;
    currentRole = 'primary';
    currentPrimary = null;
    recordsRefreshId += 1;
    transfersRefreshId += 1;
    dnssecRefreshId += 1;
    editingRecord = null;
    allRecords = [];
    clearSecondaryUI();
    if (trap) {
        trap.release();
        trap = null;
    }
}

/** The zones a Node hosts, from the current Topology payload when present,
 * falling back to the DNS service list when the Topology carries no
 * service_details for it. */
function zonesFromTopology(nodeName) {
    const nodes = appState.currentTopology?.nodes || [];
    const node = nodes.find((n) => n.id === nodeName);
    const details = Array.isArray(node?.service_details) ? node.service_details : [];
    const dnsDetail = details.find((d) => d && d.name === 'dns');
    if (dnsDetail && Array.isArray(dnsDetail.zones) && dnsDetail.zones.length > 0) {
        return dnsDetail.zones;
    }
    return null;
}

function formatResponseError(data, fallback) {
    const detail = data && data.detail;
    if (typeof detail === 'string' && detail) return detail;
    if (Array.isArray(detail)) {
        const messages = detail.map((item) => {
            if (typeof item === 'string') return item;
            if (item && typeof item.msg === 'string') return item.msg;
            if (item && typeof item.message === 'string') return item.message;
            return JSON.stringify(item);
        });
        return messages.filter(Boolean).join('; ') || fallback;
    }
    if (detail && typeof detail === 'object') {
        if (typeof detail.message === 'string') return detail.message;
        if (typeof detail.error === 'string') return detail.error;
        return JSON.stringify(detail);
    }
    return (data && typeof data.message === 'string' && data.message) || fallback;
}

async function loadZones() {
    const node = currentNode;
    if (!node) return;

    let zones = zonesFromTopology(node);
    if (!zones) {
        let response;
        try {
            response = await getDnsNodes();
        } catch (error) {
            if (node === currentNode) {
                setRecordsStatus(`Can't reach the server: ${error.message || error}`, true);
            }
            return;
        }
        if (node !== currentNode) return;
        let data = null;
        try {
            data = await response.json();
        } catch (_) { /* fall through with data === null */ }
        if (!response.ok) {
            setRecordsStatus(
                formatResponseError(data, `Request failed (${response.status})`),
                true,
            );
            return;
        }
        const entry = ((data && data.nodes) || []).find((n) => n.node === node);
        zones = (entry && entry.zones) || [];
    }

    if (node !== currentNode) return;
    renderZoneOptions(zones);
    if (zones.length > 0) {
        currentZone = zones[0];
        const select = document.getElementById('dns-zone-select');
        if (select) select.value = currentZone;
        void refreshRecords();
        void refreshZoneStatus();
        void refreshDnssec();
    } else {
        setRecordsStatus('This Node hosts no Zones.', false);
    }
}

function renderZoneOptions(zones) {
    const select = document.getElementById('dns-zone-select');
    if (!select) return;
    select.replaceChildren();
    zones.forEach((zone) => {
        const option = document.createElement('option');
        option.value = zone;
        option.textContent = zone;
        select.appendChild(option);
    });
}

async function refreshRecords() {
    const node = currentNode;
    const zone = currentZone;
    if (!node || !zone) return;
    const requestId = ++recordsRefreshId;

    let response;
    try {
        response = await getDnsRecords(node, zone);
    } catch (error) {
        if (node === currentNode) {
            setRecordsStatus(`Can't reach the server: ${error.message || error}`, true);
        }
        return;
    }

    if (node !== currentNode || zone !== currentZone || requestId !== recordsRefreshId) return;

    let data = null;
    try {
        data = await response.json();
    } catch (_) { /* fall through with data === null */ }

    if (node !== currentNode || zone !== currentZone || requestId !== recordsRefreshId) return;

    if (!response.ok) {
        setRecordsStatus(
            formatResponseError(data, `Request failed (${response.status})`),
            true,
        );
        return;
    }

    allRecords = (data && data.records) || [];
    renderRecords(allRecords);
}

function showSignatureRecords() {
    const toggle = document.getElementById('dns-show-dnssec-records');
    return Boolean(toggle && toggle.checked);
}

function renderRecords(records) {
    const tbody = document.getElementById('dns-records-tbody');
    if (!tbody) return;
    const shown = visibleRecords(records, showSignatureRecords());
    if (records.length === 0) {
        setRecordsStatus('No Records in this Zone yet.', false);
    } else if (shown.length === 0) {
        setRecordsStatus(
            'Only signature Records are in this Zone. Tick the toggle above to show them.',
            false,
        );
    } else {
        setRecordsStatus('', false);
    }
    const isSecondary = currentRole === 'secondary';
    const actionsTh = document.getElementById('dns-records-actions-th');
    if (actionsTh) actionsTh.hidden = isSecondary;

    patchTableRows(tbody, shown.map((record) => {
        const cells = [
            record.owner || '—',
            record.ttl != null ? String(record.ttl) : '—',
            record.type || '—',
            record.data || '—',
        ];
        if (!isSecondary) {
            cells.push(actionsCell(tbody, record));
        }
        return {
            key: `${record.owner}|${record.type}|${record.data}`,
            cells,
        };
    }));
}

/** The row's Actions cell, rebuilt only when the Record it carries changed:
 * reusing the node across polls keeps a screen reader's place in the table
 * and any focus on the buttons stable, the same contract the DHCP Leases
 * panel's client cell has. */
function actionsCell(tbody, record) {
    const key = `${record.owner}|${record.type}|${record.data}`;
    const existing = tbody.querySelector(
        `.dns-record-actions[data-key="${CSS.escape(key)}"]`
    );
    if (existing && existing.dataset.ttl === String(record.ttl)) return existing;

    const cell = existing || document.createElement('div');
    if (!existing) {
        cell.className = 'dns-record-actions';
        cell.dataset.key = key;
    }
    cell.dataset.ttl = String(record.ttl);
    cell.replaceChildren();

    const editBtn = document.createElement('button');
    editBtn.type = 'button';
    editBtn.className = 'dns-record-action-btn';
    editBtn.textContent = 'Edit';
    editBtn.setAttribute('aria-label', `Edit record ${record.owner} ${record.type}`);
    editBtn.addEventListener('click', (e) => startEditRecord(record, e.currentTarget));
    cell.appendChild(editBtn);

    const deleteBtn = document.createElement('button');
    deleteBtn.type = 'button';
    deleteBtn.className = 'dns-record-action-btn dns-record-delete-btn';
    deleteBtn.textContent = 'Delete';
    deleteBtn.setAttribute('aria-label', `Delete record ${record.owner} ${record.type}`);
    deleteBtn.addEventListener('click', () => { void handleRecordDelete(record); });
    cell.appendChild(deleteBtn);

    return cell;
}

