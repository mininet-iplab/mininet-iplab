// DNS Service panel — the modal a Learner opens from a Node's DNS badge to
// manage a Zone's Resource Records, watch the Service's live query activity,
// and inspect the Zone's SOA serial and role.
//
// Records are the server's own commit log, not Interface state (see
// mniplab/dns/record_service.py): the table here is what Knot holds, applied
// the moment the POST/DELETE succeeds. Mutations are broadcast to every
// open panel over the topology WebSocket (type "DNS_RECORD_UPDATED"), so a
// Record another session writes replaces what this panel shows — the
// broadcast handler below is last-write-wins, the same contract the DHCP
// pools panel has with "dhcp_pool_update".
//
// Query counters (Knot's mod-stats) are poll-only; the interval matches the
// DHCP Leases panel and the instructor Sessions/Terminals panels.
//
// A signed Zone carries two kinds of Record. The ones a Learner authored are
// in Knot's commit log the same as any other; the RRSIG and NSEC chain beside
// them is the signer's own output, rewritten on every change and on every key
// rollover. The table hides that second kind by default (see visibleRecords)
// because a six-record teaching Zone signs into forty, and the Records a
// Learner is looking for disappear into the noise. The toggle brings them
// back for the step of the lab that is about them.

